// Row shapes for the tables in supabase/migrations. Keep in sync by hand
// (or replace with `supabase gen types` output once a project exists).

export type HouseholdRole = "owner" | "member";

export const ACCOUNT_TYPES = [
  "checking",
  "savings",
  "credit_card",
  "brokerage",
  "retirement",
  "hsa",
  "crypto",
  "mortgage",
  "other",
  "property",
  "vehicle",
  "loan",
] as const;
export type AccountType = (typeof ACCOUNT_TYPES)[number];

export const TRANSACTION_TYPES = [
  "expense",
  "income",
  "transfer",
  "credit_card_payment",
  "refund",
  "adjustment",
  "investment_contribution",
  "investment_withdrawal",
  "reimbursement",
] as const;
export type TransactionType = (typeof TRANSACTION_TYPES)[number];

export type ExpenseType = "fixed" | "variable" | "discretionary" | "irregular";
export type ReviewStatus = "auto_categorized" | "needs_review" | "reviewed";
export type ConfidenceLevel = "high" | "medium" | "low";

export interface ProfileRow {
  id: string;
  email: string;
  name: string;
  created_at: string;
}

export interface HouseholdRow {
  id: string;
  name: string;
  /** transactions before this date are history (Catch-up), not Sunday Review */
  review_starts_on: string | null;
  created_at: string;
}

export interface HouseholdMemberRow {
  household_id: string;
  user_id: string;
  role: HouseholdRole;
  created_at: string;
}

export interface AccountRow {
  id: string;
  household_id: string;
  owner_user_id: string | null;
  institution: string;
  account_name: string;
  account_type: AccountType;
  last_four: string | null;
  is_active: boolean;
  created_at: string;
}

export interface CategoryRow {
  id: string;
  household_id: string;
  parent_id: string | null;
  name: string;
  default_expense_type: ExpenseType | null;
  sort_order: number;
  is_active: boolean;
  created_at: string;
}

export interface TransactionRow {
  id: string;
  household_id: string;
  account_id: string;
  person_id: string | null;
  transaction_date: string; // YYYY-MM-DD
  posting_date: string | null;
  original_description: string;
  normalized_merchant: string;
  amount: number; // negative = money out, positive = money in
  transaction_type: TransactionType;
  category_id: string | null;
  subcategory_id: string | null;
  expense_type: ExpenseType | null;
  is_recurring: boolean;
  is_transfer: boolean; // generated by the database from transaction_type
  review_status: ReviewStatus;
  categorization_confidence: ConfidenceLevel | null;
  categorization_reason: string | null;
  notes: string | null;
  source_file: string | null;
  source_hash: string | null;
  /** the bank's own category label, when the export has one */
  bank_category: string | null;
  /** for a payback between members: the other person (the sender, on the receiving row) */
  counterparty_id: string | null;
  /** typed in by a person rather than imported */
  is_manual: boolean;
  /** a hand-added entry expected to appear in a later bank download */
  awaiting_post: boolean;
  /** only the transaction's person can see it (enforced by the database) */
  is_private: boolean;
  /** from this date it is visible to everyone again; null = until changed */
  private_until: string | null;
  created_at: string;
  updated_at: string;
}

export type RuleMatchType = "merchant" | "description" | "bank_category";
export type RuleSource = "default" | "learned" | "manual" | "ai";

export interface CategorizationRuleRow {
  id: string;
  household_id: string;
  match_type: RuleMatchType;
  /** lowercased */
  pattern: string;
  category_id: string;
  subcategory_id: string;
  auto_apply: boolean;
  source: RuleSource;
  created_at: string;
  updated_at: string;
}

export type BudgetScope = "everyone" | "person" | "shared";
export const BUDGET_KINDS = ["fixed", "variable", "allowance", "sinking_fund"] as const;
export type BudgetKind = (typeof BUDGET_KINDS)[number];

export interface BudgetLineRow {
  id: string;
  household_id: string;
  scope: BudgetScope;
  person_id: string | null;
  category_id: string;
  subcategory_id: string | null;
  kind: BudgetKind;
  amount: number;
  /** first day of the first month this line applies, YYYY-MM-01 */
  starts_month: string;
  /** first day of the last month it applies, or null while still in effect */
  ends_month: string | null;
  created_at: string;
}

export type RecurringStatus = "not_recurring" | "stopped";

export interface RecurringOverrideRow {
  household_id: string;
  recurring_key: string;
  status: RecurringStatus;
  created_at: string;
}

export type BalanceSource = "manual" | "import";

export interface AccountBalanceRow {
  id: string;
  household_id: string;
  account_id: string;
  as_of: string;
  /** what an asset is worth, or what is owed on a debt */
  balance: number;
  source: BalanceSource;
  created_at: string;
}

export const INCOME_FREQUENCIES = ["weekly", "biweekly", "semimonthly", "monthly"] as const;
export type IncomeFrequency = (typeof INCOME_FREQUENCIES)[number];

export interface IncomeSourceRow {
  id: string;
  household_id: string;
  /** null = shared income */
  person_id: string | null;
  name: string;
  amount: number;
  frequency: IncomeFrequency;
  /** any real pay date on the schedule */
  anchor_date: string;
  /** for twice a month: the other day of the month */
  second_day: number | null;
  is_active: boolean;
  created_at: string;
}

/** What the database accepts on insert (is_transfer is generated). */
export type TransactionInsert = Omit<TransactionRow, "is_transfer">;

export function toTransactionInsert(row: TransactionRow): TransactionInsert {
  const copy: Partial<TransactionRow> = { ...row };
  delete copy.is_transfer;
  return copy as TransactionInsert;
}

export function isTransferType(type: TransactionType): boolean {
  return type === "transfer" || type === "credit_card_payment";
}
